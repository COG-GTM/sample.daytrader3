package com.ibm.websphere.samples.daytrader.util;

/**
 * Unchecked exception replacing the container-specific {@code javax.ejb.EJBException}
 * used by the legacy EJB implementation. Throwing a {@code RuntimeException} from a
 * Spring {@code @Transactional} method triggers automatic rollback, preserving the
 * EJB's "system exception rolls back the transaction" semantics.
 */
public class TradeException extends RuntimeException {

    private static final long serialVersionUID = 1L;

    public TradeException(String message) {
        super(message);
    }

    public TradeException(String message, Throwable cause) {
        super(message, cause);
    }

    public TradeException(Throwable cause) {
        super(cause);
    }
}
